    [Fact]
    public void EveryEffect_WorkedOutFromTheSurface_IsTheColumnsOwn_ExactlyToTheBit()
    {
        var states = States().ToList();
        Assert.Equal(Recorded.Length, states.Count);
        for (int i = 0; i < states.Count; i++)
        {
            var (tag, g, sub) = states[i];
            var f = Recorded[i].Split('|');
            Assert.Equal(f[0], tag);
            Assert.Equal(int.Parse(f[13], CultureInfo.InvariantCulture), g.Layers.Count);
            var s = Ground.SurfaceOf(g, sub);
            string[] actual =
            [
                tag, R(s.TraversalFactor), R(s.HazardDelta), R(s.SearchFactor(0, 0.3)), R(s.SearchFactor(0.02, 0.05)),
                R(s.ContactWettingRate(SurfaceContact.Walking, 0)), R(s.ContactWettingRate(SurfaceContact.Walking, 0.05)),
                R(s.ContactWettingRate(SurfaceContact.RestingOnGround, 0.2)), R(s.ContactWettingRate(SurfaceContact.WorkingOnGround, 0)),
                R(s.SnowDepthM), R(s.WaterDepthM), R(s.DrinkableWaterM), s.Iced.ToString(), f[13],
            ];
            Assert.Equal(Recorded[i], string.Join("|", actual));
        }
    }

    /// Every passable tile of seed 17 on three days: each effect, the map's five values and the animal's water,
    /// hashed, as the world reads gave them before the surface: the frozen-river and open-lake rules are in it.
    [Fact]
    public void Underfoot_OnEveryTile_ReadsTheRecordedGround()
    {
        var w = TestWorlds.New(17);
        var m = Map.Of(w);
        var sb = new StringBuilder();
        foreach (long minute in new[] { 3 * 1440L + 7, 40 * 1440L + 290, 75 * 1440L + 1000 })
        {
            w.Minute = minute;
            for (int x = 0; x < m.Width; x++)
                for (int y = 0; y < m.Height; y++)
                {
                    var t = new TileId(x, y);
                    if (!m.TerrainAt(t).IsPassable()) continue;
                    var s = Ground.Underfoot(w, t);
                    sb.Append($"{x},{y}|{R(s.TraversalFactor)}|{R(Traversal.SurfaceHazardDelta(w, t))}|{R(s.SearchFactor(0, 0.3))}"
                        + $"|{R(s.ContactWettingRate(SurfaceContact.Walking, 0))}|{R(s.ContactWettingRate(SurfaceContact.RestingOnGround, 0.2))}"
                        + $"|{R(s.SnowDepthM)}|{s.Crusted}|{R(s.MudLevel)}|{R(s.WaterDepthM)}|{s.Iced}|{R(s.SnowDepthM)}|{R(s.DrinkableWaterM)}\n");
                }
        }
        Assert.Equal("ecc410e562e1e3ad89fa0c3c732b8e4d4b3a6f4c630385c77422d9d297febb65",
            Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString()))));
    }

    /// States the effects are checked on: the golden weathers on every substrate, slush, crust, and a pond
    /// under several snow layers, frozen and liquid (where adding depths in another order would show).
    static IEnumerable<(string Tag, GroundState State, SubstrateProfile Sub)> States()
    {
        var snow = new SurfaceWeather(15, 0.2, 0, 0.005 / 60, 0);
        var thaw = new SurfaceWeather(45, 0.3, 0.5, 0, 0);
        var freeze = new SurfaceWeather(10, 0.4, 0, 0, 0);
        var rain = new SurfaceWeather(40, 0.1, 0, 0, 0.010 / 60);
        var dry = new SurfaceWeather(45, 0.5, 0.4, 0, 0);
        var still = new SurfaceWeather(25, 0.1, 0, 0, 0);
        (string, SubstrateProfile)[] subs =
        [
            ("loam", SubstrateProfile.Loam), ("forestFloor", SubstrateProfile.ForestFloor), ("slope", SubstrateProfile.Slope),
            ("rock", SubstrateProfile.Rock), ("peat", SubstrateProfile.Peat), ("iceSheet", SubstrateProfile.IceSheet),
        ];
        foreach (var (name, sub) in subs)
        {
            var g = Ground.Baseline(sub);
            yield return ($"{name}-baseline", Clone(g), sub);
            foreach (var (step, weather, minutes) in new[] { ("snow", snow, 2 * 1440), ("slush", thaw, 300), ("thaw", thaw, 2 * 1440), ("crust", freeze, 1440),
                ("rain", rain, 1440), ("wet", still, 60), ("dry", dry, 2 * 1440), ("frozen", freeze, 720) })
            {
                Ground.Advance(g, sub, minutes, weather);
                yield return ($"{name}-{step}", Clone(g), sub);
            }
        }
        foreach (double frozenMinutes in new[] { 0.0, 60, 600 })
        {
            var peat = SubstrateProfile.Peat;
            var p = Ground.Baseline(peat, 0);
            Ground.AddWater(p, peat, 0.12);
            Ground.Advance(p, peat, 1, still);
            if (frozenMinutes > 0) Ground.Advance(p, peat, (int)frozenMinutes, freeze);
            var settle = frozenMinutes > 0 ? still : new SurfaceWeather(33, 0.1, 0, 0, 0);
            Ground.AddSnow(p, peat, 0.003);
            Ground.Advance(p, peat, 3 * 1440, settle);
            Ground.AddSnow(p, peat, 0.004);
            Ground.Advance(p, peat, 1440, settle);
            Ground.AddSnow(p, peat, 0.0017);
            yield return ($"pond-under-snow-{frozenMinutes}", Clone(p), peat);
            Ground.Compact(p, peat, 0.6);
            yield return ($"pond-under-packed-snow-{frozenMinutes}", Clone(p), peat);
        }
        var deep = Ground.Baseline(SubstrateProfile.IceSheet);
        deep.Layers.Add(new SurfaceLayer { Material = SurfaceMaterial.Water, ThicknessM = Ground.MaxStandingWaterDepthM, WaterSaturationPct = 1 });
        yield return ("open-water", deep, SubstrateProfile.IceSheet);
    }

    static GroundState Clone(GroundState s) => new()
    {
        Layers = [.. s.Layers.Select(l => new SurfaceLayer
        {
            Material = l.Material, ThicknessM = l.ThicknessM, CompactionPct = l.CompactionPct,
            WaterSaturationPct = l.WaterSaturationPct, FrozenFractionPct = l.FrozenFractionPct,
        })],
    };

    static string R(double d) => d.ToString("R", CultureInfo.InvariantCulture);
